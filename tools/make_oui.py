#!/usr/bin/env python3
"""Builds esp32-firmware/src/oui_table.h from Wireshark's manufacturer database.

Usage: make_oui.py <manuf file> <output header>
The manuf file is published at https://www.wireshark.org/download/automated/data/manuf
Only whole 24-bit blocks are used. Company names are stripped of legal suffixes and cut to
20 characters, then stored once each in a name pool.
"""
import re
import sys

MAX_NAME = 20
SUFFIXES = re.compile(
    r"[\s,]+(inc|incorporated|co|corp|corporation|company|ltd|limited|llc|gmbh|ag|sa|srl|bv|ab|oy|as|plc|pte|pty|kg|"
    r"s\.a|s\.p\.a|spa|nv|kk|a/s|l\.l\.c|l\.p|lp|sas|s\.r\.l|international|holdings?|group)\.?$",
    re.I,
)


def clean(name):
    name = name.strip().strip('"')
    for _ in range(4):
        shorter = SUFFIXES.sub("", name).strip(" ,.")
        if shorter == name or not shorter:
            break
        name = shorter
    name = "".join(c if 32 <= ord(c) < 127 and c not in '"\\' else "?" for c in name)
    return name[:MAX_NAME].strip()


def main():
    src, dst = sys.argv[1], sys.argv[2]
    entries = {}
    for line in open(src, encoding="utf-8", errors="replace"):
        if line.startswith("#") or not line.strip():
            continue
        parts = line.rstrip("\n").split("\t")
        prefix = parts[0].strip()
        if not re.fullmatch(r"([0-9A-Fa-f]{2}:){2}[0-9A-Fa-f]{2}", prefix):
            continue  # skip sub-blocks (/28, /36) and other forms
        name = clean(parts[2] if len(parts) > 2 and parts[2].strip() else parts[1])
        if name:
            entries[int(prefix.replace(":", ""), 16)] = name

    pool, offsets = bytearray(), {}
    for name in sorted(set(entries.values())):
        offsets[name] = len(pool)
        pool += name.encode("ascii") + b"\0"
    keys = sorted(entries)

    with open(dst, "w") as out:
        out.write("// Generated by tools/make_oui.py from Wireshark's manuf database. Do not edit.\n")
        out.write("#pragma once\n#include <stdint.h>\n#include <pgmspace.h>\n\n")
        out.write(f"#define OUI_COUNT {len(keys)}\n\n")
        out.write("// Sorted 24-bit prefixes, three bytes each\n")
        out.write("static const uint8_t oui_prefix[] PROGMEM = {\n")
        for i in range(0, len(keys), 8):
            row = ",".join(f"{(k >> 16) & 255},{(k >> 8) & 255},{k & 255}" for k in keys[i : i + 8])
            out.write(row + ",\n")
        out.write("};\n\n// Offset of each prefix's company name in oui_names\n")
        out.write("static const uint32_t oui_name_offset[] PROGMEM = {\n")
        for i in range(0, len(keys), 16):
            out.write(",".join(str(offsets[entries[k]]) for k in keys[i : i + 16]) + ",\n")
        out.write("};\n\nstatic const char oui_names[] PROGMEM =\n")
        text = pool.decode("ascii")
        for i in range(0, len(text), 96):
            chunk = text[i : i + 96].replace("\0", "\\0")
            # keep a digit after an escape from being read as part of it
            chunk = re.sub(r"\\0(?=[0-9])", '\\\\0""', chunk)
            out.write(f'    "{chunk}"\n')
        out.write(";\n")
    print(f"{len(keys)} prefixes, {len(offsets)} names, pool {len(pool)} bytes, "
          f"flash about {(len(keys) * 7 + len(pool)) // 1024} KB")


if __name__ == "__main__":
    main()
